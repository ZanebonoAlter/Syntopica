// TestDeleteFeedCascadeRollsBackOnCleanupFailure is the fail-closed half of the
// table-probe boundary (design D2): only table existence is guarded, not columns,
// so a user_preferences table without feed_id makes the cleanup DELETE itself
// error. The whole transaction must roll back — the feed, its articles and its
// reading behaviors (deleted earlier in the same transaction) all stay as they
// were. The malformed shape is the failure injection: a Postgres table can be
// renamed/replaced but never legitimately lose this column.
func TestDeleteFeedCascadeRollsBackOnCleanupFailure(t *testing.T) {
	db := testutil.SetupTestDB(t)
	require.NoError(t, db.Exec(`CREATE TABLE user_preferences (id bigint PRIMARY KEY, category_id bigint)`).Error)
	t.Cleanup(func() {
		require.NoError(t, db.Exec("DROP TABLE IF EXISTS user_preferences").Error)
	})
	feed, articles := seedRefFeed(t, db, "rollback-feed", 1)
	require.NoError(t, db.Exec(`INSERT INTO reading_behaviors (article_id, feed_id, event_type, created_at)
		VALUES (?, ?, 'favorite', now())`, articles[0].ID, feed.ID).Error)

	err := repository.NewReaderRepository(db).DeleteFeedCascade(feed.ID)
	require.Error(t, err)
	require.Contains(t, err.Error(), "feed_id",
		"the failure is the missing cleanup column, so the rollback is the expected path")

	var feedCount int64
	require.NoError(t, db.Model(&models.Feed{}).Where("id = ?", feed.ID).Count(&feedCount).Error)
	require.EqualValues(t, 1, feedCount, "the feed row survives the rolled-back transaction")
	var articleCount int64
	require.NoError(t, db.Model(&models.Article{}).Where("feed_id = ?", feed.ID).Count(&articleCount).Error)
	require.EqualValues(t, 1, articleCount, "its articles survive the rolled-back transaction")
	var behaviorCount int64
	require.NoError(t, db.Model(&models.ReadingBehavior{}).Where("feed_id = ?", feed.ID).Count(&behaviorCount).Error)
	require.EqualValues(t, 1, behaviorCount, "the earlier reading_behaviors delete is rolled back too")
}

// TestDeleteCategoryCascadeRemovesReferenceRows covers the category path: the
// feeds' reading behaviors and the user_preferences rows that name either the
// feeds or the category itself are cleared before the articles go, because a
// surviving reading_behaviors row would block the article deletion through
// fk_reading_behaviors_article.
func TestDeleteCategoryCascadeRemovesReferenceRows(t *testing.T) {
	db := testutil.SetupTestDB(t)
	createUserPreferencesTable(t, db)
	createLegacyReadingBehaviorFKs(t, db)
	first, firstArticles := seedRefFeed(t, db, "cat-refs-first", 1)
	second, secondArticles := seedRefFeed(t, db, "cat-refs-second", 1)
	category := seedRefCategory(t, db, "cat-refs", first.ID, second.ID)

	require.NoError(t, db.Exec(`INSERT INTO reading_behaviors (article_id, feed_id, event_type, created_at)
		VALUES (?, ?, 'favorite', now()), (?, ?, 'read', now())`,
		firstArticles[0].ID, first.ID, secondArticles[0].ID, second.ID).Error)
	seedUserPreference(t, db, refUintPtr(first.ID), nil)
	seedUserPreference(t, db, refUintPtr(second.ID), refUintPtr(category.ID))
	seedUserPreference(t, db, nil, refUintPtr(category.ID)) // category-level row, no feed

	require.NoError(t, repository.NewReaderRepository(db).DeleteCategoryCascade(category.ID))

	var categoryCount int64
	require.NoError(t, db.Model(&models.Category{}).Where("id = ?", category.ID).Count(&categoryCount).Error)
	require.Zero(t, categoryCount, "the category row is deleted")
	var feedCount int64
	require.NoError(t, db.Model(&models.Feed{}).Where("id IN ?", []uint{first.ID, second.ID}).Count(&feedCount).Error)
	require.Zero(t, feedCount, "its feeds are deleted")
	var articleCount int64
	require.NoError(t, db.Model(&models.Article{}).Where("feed_id IN ?", []uint{first.ID, second.ID}).Count(&articleCount).Error)
	require.Zero(t, articleCount, "its articles are deleted")
	var behaviorCount int64
	require.NoError(t, db.Model(&models.ReadingBehavior{}).Where("feed_id IN ?", []uint{first.ID, second.ID}).Count(&behaviorCount).Error)
	require.Zero(t, behaviorCount, "its feeds' reading behaviors are deleted")
	require.Zero(t, countFeedUserPreferences(t, db, first.ID), "the first feed's preferences are deleted")
	require.Zero(t, countFeedUserPreferences(t, db, second.ID), "the second feed's preferences are deleted")
	require.Zero(t, countCategoryUserPreferences(t, db, category.ID), "the category-level preference row is deleted")
}


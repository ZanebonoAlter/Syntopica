// refUintPtr boxes an id for the nullable feed_id/category_id columns of the
// rebuilt user_preferences fixture.
func refUintPtr(v uint) *uint {
	return &v
}

// createUserPreferencesTable rebuilds the pre-discovery-v2 table the delete
// paths must tolerate. The golden test schema has no such table — the test
// migration path enables MIGRATIONS_ALLOW_DESTRUCTIVE, so 20260725_0001 really
// drops it — while a production or long-lived database still carries it, with
// exactly these NO ACTION foreign keys: they are what used to roll every feed
// and category deletion transaction back with a foreign-key violation. The DDL
// is test-fixture only (isolated testcontainer) and the table is dropped again
// when the test ends, so the shared golden schema stays as the migrations built
// it.
func createUserPreferencesTable(t *testing.T, db *gorm.DB) {
	t.Helper()
	require.NoError(t, db.Exec(`CREATE TABLE user_preferences (
		id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		feed_id bigint,
		category_id bigint,
		preference_score numeric DEFAULT 0,
		avg_reading_time bigint DEFAULT 0,
		interaction_count bigint DEFAULT 0,
		scroll_depth_avg numeric DEFAULT 0,
		last_interaction_at timestamptz,
		created_at timestamptz,
		updated_at timestamptz,
		CONSTRAINT fk_user_preferences_feed FOREIGN KEY (feed_id) REFERENCES feeds(id),
		CONSTRAINT fk_user_preferences_category FOREIGN KEY (category_id) REFERENCES categories(id)
	)`).Error)
	t.Cleanup(func() {
		// ResetTestData truncates by catalog lookup, so a leftover fixture would
		// silently become part of every later reset in this package.
		require.NoError(t, db.Exec("DROP TABLE IF EXISTS user_preferences").Error)
	})
}

// dropUserPreferencesTable puts the database into the "narrow deployment /
// DROP migration executed" state. The golden schema already starts there, but a
// previous test in this process may have rebuilt the fixture table.
func dropUserPreferencesTable(t *testing.T, db *gorm.DB) {
	t.Helper()
	require.NoError(t, db.Exec("DROP TABLE IF EXISTS user_preferences").Error)
	require.False(t, db.Migrator().HasTable("user_preferences"),
		"the missing-table scenarios must really run without the table")
}

// createLegacyReadingBehaviorFKs restores the AutoMigrate-era NO ACTION foreign
// keys the golden schema deliberately omits
// (DisableForeignKeyConstraintWhenMigrating). Without them the testcontainer
// would not reproduce the production blocking: a feed/category delete that left
// reading_behaviors rows behind would succeed here while failing on a long-lived
// database. Dropped again when the test ends.
func createLegacyReadingBehaviorFKs(t *testing.T, db *gorm.DB) {
	t.Helper()
	require.NoError(t, db.Exec(`ALTER TABLE reading_behaviors
		ADD CONSTRAINT fk_reading_behaviors_feed FOREIGN KEY (feed_id) REFERENCES feeds(id),
		ADD CONSTRAINT fk_reading_behaviors_article FOREIGN KEY (article_id) REFERENCES articles(id)`).Error)
	t.Cleanup(func() {
		require.NoError(t, db.Exec(`ALTER TABLE reading_behaviors
			DROP CONSTRAINT IF EXISTS fk_reading_behaviors_feed,
			DROP CONSTRAINT IF EXISTS fk_reading_behaviors_article`).Error)
	})
}

// seedUserPreference inserts one legacy reference row. Both owner columns are
// nullable in the historical schema: a feed-level row names feed_id, a
// category-level row names only category_id.
func seedUserPreference(t *testing.T, db *gorm.DB, feedID, categoryID *uint) {
	t.Helper()
	require.NoError(t, db.Exec(`INSERT INTO user_preferences (feed_id, category_id, preference_score, created_at, updated_at)
		VALUES (?, ?, 0.5, now(), now())`, feedID, categoryID).Error)
}

func countFeedUserPreferences(t *testing.T, db *gorm.DB, feedID uint) int64 {
	t.Helper()
	var count int64
	require.NoError(t, db.Raw("SELECT count(*) FROM user_preferences WHERE feed_id = ?", feedID).Scan(&count).Error)
	return count
}

func countCategoryUserPreferences(t *testing.T, db *gorm.DB, categoryID uint) int64 {
	t.Helper()
	var count int64
	require.NoError(t, db.Raw("SELECT count(*) FROM user_preferences WHERE category_id = ?", categoryID).Scan(&count).Error)
	return count
}

func countUnownedUserPreferences(t *testing.T, db *gorm.DB) int64 {
	t.Helper()
	var count int64
	require.NoError(t, db.Raw(
		"SELECT count(*) FROM user_preferences WHERE feed_id IS NULL AND category_id IS NULL").Scan(&count).Error)
	return count
}

// TestDeleteFeedCascadeRemovesUserPreferences covers the failure this change
// exists for: a feed cited by the legacy user_preferences table used to make the
// whole deletion transaction roll back through fk_user_preferences_feed, so the
// user saw an error and the feed stayed in the library.
func TestDeleteFeedCascadeRemovesUserPreferences(t *testing.T) {
	db := testutil.SetupTestDB(t)
	createUserPreferencesTable(t, db)
	deleted, deletedArticles := seedRefFeed(t, db, "pref-delete", 2)
	kept, keptArticles := seedRefFeed(t, db, "pref-keep", 1)

	require.NoError(t, db.Exec(`INSERT INTO reading_behaviors (article_id, feed_id, event_type, created_at)
		VALUES (?, ?, 'favorite', now()), (?, ?, 'favorite', now())`,
		deletedArticles[0].ID, deleted.ID, keptArticles[0].ID, kept.ID).Error)
	seedUserPreference(t, db, refUintPtr(deleted.ID), nil)
	seedUserPreference(t, db, refUintPtr(deleted.ID), nil)
	seedUserPreference(t, db, refUintPtr(kept.ID), nil)
	seedUserPreference(t, db, nil, nil) // ownerless row: never in the delete scope

	require.NoError(t, repository.NewReaderRepository(db).DeleteFeedCascade(deleted.ID))

	var feedCount int64
	require.NoError(t, db.Model(&models.Feed{}).Where("id = ?", deleted.ID).Count(&feedCount).Error)
	require.Zero(t, feedCount, "the referenced feed is deleted")
	var articleCount int64
	require.NoError(t, db.Model(&models.Article{}).Where("feed_id = ?", deleted.ID).Count(&articleCount).Error)
	require.Zero(t, articleCount, "its articles are deleted")
	var behaviorCount int64
	require.NoError(t, db.Model(&models.ReadingBehavior{}).Where("feed_id = ?", deleted.ID).Count(&behaviorCount).Error)
	require.Zero(t, behaviorCount, "its reading behaviors are deleted")
	require.Zero(t, countFeedUserPreferences(t, db, deleted.ID), "its user_preferences rows are deleted")

	var keptFeedCount int64
	require.NoError(t, db.Model(&models.Feed{}).Where("id = ?", kept.ID).Count(&keptFeedCount).Error)
	require.EqualValues(t, 1, keptFeedCount, "another feed survives")
	var keptBehaviorCount int64
	require.NoError(t, db.Model(&models.ReadingBehavior{}).Where("feed_id = ?", kept.ID).Count(&keptBehaviorCount).Error)
	require.EqualValues(t, 1, keptBehaviorCount, "another feed's reading behaviors survive")
	require.EqualValues(t, 1, countFeedUserPreferences(t, db, kept.ID), "another feed's preferences survive")
	require.EqualValues(t, 1, countUnownedUserPreferences(t, db), "an ownerless preference row survives")
}

// TestDeleteFeedCascadeRemovesReadingBehaviors covers the reading_behaviors half
// without the fixture table: the rows must vanish with the feed regardless of
// whether this database carries fk_reading_behaviors_feed.
func TestDeleteFeedCascadeRemovesReadingBehaviors(t *testing.T) {
	db := testutil.SetupTestDB(t)
	dropUserPreferencesTable(t, db)
	createLegacyReadingBehaviorFKs(t, db)
	feed, articles := seedRefFeed(t, db, "behavior-delete", 2)
	_, keepArticles := seedRefFeed(t, db, "behavior-keep", 1)

	require.NoError(t, db.Exec(`INSERT INTO reading_behaviors (article_id, feed_id, event_type, created_at)
		VALUES (?, ?, 'favorite', now()), (?, ?, 'read', now()), (?, ?, 'favorite', now())`,
		articles[0].ID, feed.ID, articles[1].ID, feed.ID, keepArticles[0].ID, keepArticles[0].FeedID).Error)

	require.NoError(t, repository.NewReaderRepository(db).DeleteFeedCascade(feed.ID))

	var behaviorCount int64
	require.NoError(t, db.Model(&models.ReadingBehavior{}).Where("feed_id = ?", feed.ID).Count(&behaviorCount).Error)
	require.Zero(t, behaviorCount, "the deleted feed's reading behaviors are gone")
	var keptBehaviorCount int64
	require.NoError(t, db.Model(&models.ReadingBehavior{}).Where("feed_id = ?", keepArticles[0].FeedID).Count(&keptBehaviorCount).Error)
	require.EqualValues(t, 1, keptBehaviorCount, "another feed's reading behaviors survive")
}


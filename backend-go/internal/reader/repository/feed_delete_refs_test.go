// TestDeleteCategoryCascadeLeavesOutsideDataAlone proves the cleanup is scoped:
// a feed filed under another category keeps its articles, its reading behaviors
// and its user_preferences rows.
func TestDeleteCategoryCascadeLeavesOutsideDataAlone(t *testing.T) {
	db := testutil.SetupTestDB(t)
	createUserPreferencesTable(t, db)
	inside, _ := seedRefFeed(t, db, "cat-scope-inside", 1)
	outside, outsideArticles := seedRefFeed(t, db, "cat-scope-outside", 1)
	category := seedRefCategory(t, db, "cat-scope", inside.ID)

	require.NoError(t, db.Exec(`INSERT INTO reading_behaviors (article_id, feed_id, event_type, created_at)
		VALUES (?, ?, 'favorite', now())`, outsideArticles[0].ID, outside.ID).Error)
	seedUserPreference(t, db, refUintPtr(outside.ID), nil)

	require.NoError(t, repository.NewReaderRepository(db).DeleteCategoryCascade(category.ID))

	var outsideFeedCount int64
	require.NoError(t, db.Model(&models.Feed{}).Where("id = ?", outside.ID).Count(&outsideFeedCount).Error)
	require.EqualValues(t, 1, outsideFeedCount, "a feed outside the category survives")
	var outsideArticleCount int64
	require.NoError(t, db.Model(&models.Article{}).Where("feed_id = ?", outside.ID).Count(&outsideArticleCount).Error)
	require.EqualValues(t, 1, outsideArticleCount, "its articles survive")
	var outsideBehaviorCount int64
	require.NoError(t, db.Model(&models.ReadingBehavior{}).Where("feed_id = ?", outside.ID).Count(&outsideBehaviorCount).Error)
	require.EqualValues(t, 1, outsideBehaviorCount, "its reading behaviors survive")
	require.EqualValues(t, 1, countFeedUserPreferences(t, db, outside.ID), "its preferences survive")
}
